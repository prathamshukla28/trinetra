// Writes the compare report (markdown + HTML) to reports/.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const REPORT_DIR = path.join(ROOT, "reports");
const esc = (s) => String(s ?? "").replace(/[&<>]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;" })[c]);

function listBlock(title, items) {
  if (!items.length) return [`**${title}:** none`, ""];
  return [`**${title}** (${items.length}):`, "", ...items.map((n) => `- \`${n}\``), ""];
}

function markdown(d) {
  const L = [];
  L.push(`# Trinetra compare — ${d.aName} → ${d.bName}`, "");
  L.push(`_Generated ${new Date().toISOString()}_`, "");
  L.push(`## Procedures / units`, "");
  L.push(...listBlock("Added", d.procedures.added));
  L.push(...listBlock("Removed", d.procedures.removed));
  if (d.hashable) L.push(...listBlock("Changed", d.procedures.changed));
  else L.push("_Changed-function detection needs native targets (per-function hashes)._", "");
  L.push(`Unchanged: **${d.procedures.unchanged}**`, "");

  L.push(`## Security findings by category`, "");
  L.push(`| Category | ${d.aName} | ${d.bName} | Δ |`, "| --- | ---: | ---: | ---: |");
  for (const r of d.findingRows) {
    const arrow = r.delta > 0 ? `🔺 +${r.delta}` : r.delta < 0 ? `🟢 ${r.delta}` : "0";
    L.push(`| ${r.category} | ${r.a} | ${r.b} | ${arrow} |`);
  }
  L.push("", `Totals: ${d.totals.a} → ${d.totals.b}`, "");
  return L.join("\n");
}

function html(d) {
  const rows = d.findingRows
    .map((r) => {
      const cls = r.delta > 0 ? "up" : r.delta < 0 ? "down" : "";
      const arrow = r.delta > 0 ? `+${r.delta}` : r.delta;
      return `<tr><td>${esc(r.category)}</td><td>${r.a}</td><td>${r.b}</td><td class="${cls}">${arrow}</td></tr>`;
    })
    .join("");
  const ul = (items) => (items.length ? `<ul>${items.map((n) => `<li><code>${esc(n)}</code></li>`).join("")}</ul>` : `<p class="muted">none</p>`);
  return `<!doctype html><html lang="en"><head><meta charset="utf-8"/>
<meta name="viewport" content="width=device-width, initial-scale=1"/>
<title>Trinetra compare · ${esc(d.aName)} → ${esc(d.bName)}</title>
<style>
  :root{--bg:#fff;--fg:#18181b;--muted:#71717a;--card:#f4f4f5;--border:#e4e4e7;--accent:#7c3aed;--up:#e5484d;--down:#30a46c;}
  @media(prefers-color-scheme:dark){:root{--bg:#0b0b0f;--fg:#e4e4e7;--muted:#a1a1aa;--card:#18181b;--border:#27272a;--accent:#a78bfa;}}
  body{margin:0;background:var(--bg);color:var(--fg);font:15px/1.6 -apple-system,BlinkMacSystemFont,"Segoe UI",Roboto,sans-serif;}
  .wrap{max-width:860px;margin:0 auto;padding:40px 20px 80px;}
  h1{font-size:24px;}h1 .a{color:var(--accent);}
  h2{font-size:18px;margin-top:32px;border-bottom:1px solid var(--border);padding-bottom:8px;}
  .cols{display:grid;grid-template-columns:1fr 1fr 1fr;gap:16px;}
  .cols h3{font-size:13px;color:var(--muted);text-transform:uppercase;letter-spacing:.05em;}
  table{width:100%;border-collapse:collapse;margin-top:8px;}
  th,td{padding:8px 10px;border-bottom:1px solid var(--border);text-align:left;}
  td:not(:first-child),th:not(:first-child){text-align:right;}
  .up{color:var(--up);font-weight:700;}.down{color:var(--down);font-weight:700;}
  .muted{color:var(--muted);} code{word-break:break-all;}
  footer{margin-top:40px;color:var(--muted);font-size:12px;text-align:center;}
</style></head><body><div class="wrap">
<h1>🔱 <span class="a">${esc(d.aName)}</span> → ${esc(d.bName)}</h1>
<p class="muted">Generated ${new Date().toISOString()}</p>
<h2>Procedures / units</h2>
<div class="cols">
  <div><h3>Added</h3>${ul(d.procedures.added)}</div>
  <div><h3>Removed</h3>${ul(d.procedures.removed)}</div>
  <div><h3>Changed</h3>${d.hashable ? ul(d.procedures.changed) : `<p class="muted">native only</p>`}</div>
</div>
<p class="muted">Unchanged: ${d.procedures.unchanged}</p>
<h2>Security findings by category</h2>
<table><thead><tr><th>Category</th><th>${esc(d.aName)}</th><th>${esc(d.bName)}</th><th>Δ</th></tr></thead>
<tbody>${rows || `<tr><td class="muted" colspan="4">No findings in either version.</td></tr>`}</tbody></table>
<p class="muted">Totals: ${d.totals.a} → ${d.totals.b}</p>
<footer>Generated by Trinetra — the third eye that sees inside any software.</footer>
</div></body></html>`;
}

export function writeCompareReport(diff) {
  fs.mkdirSync(REPORT_DIR, { recursive: true });
  const base = `${diff.aName}-vs-${diff.bName}`.replace(/[^A-Za-z0-9_.-]/g, "_");
  const md = path.join(REPORT_DIR, `${base}.md`);
  const htmlFile = path.join(REPORT_DIR, `${base}.html`);
  fs.writeFileSync(md, markdown(diff));
  fs.writeFileSync(htmlFile, html(diff));
  return { md: path.relative(ROOT, md), html: path.relative(ROOT, htmlFile) };
}
